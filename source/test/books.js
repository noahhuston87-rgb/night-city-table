const { chromium } = require('playwright'); const fs=require('fs');
(async()=>{ const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']}); const c=await b.newContext({viewport:{width:1440,height:900}});
await c.route('**/*',r=>r.request().url().startsWith('http://localhost')?r.continue():r.abort());
await c.addInitScript(fs.readFileSync('test/fakepeer.js','utf8'));
const p=await c.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{ if(m.type()==='error' && !/Failed to load resource/.test(m.text())) errs.push(m.text()); });
await p.goto('http://localhost:8123/'); await p.fill('#myName','DM'); await p.click('#createBtn'); await p.waitForSelector('#table:not(.hidden)');
await p.click('#tabs button[data-tab=books]'); await p.waitForTimeout(150);
const [fc]=await Promise.all([p.waitForEvent('filechooser'), p.click('#booksPane .folder >> nth=0 >> text=+ PDF')]); await fc.setFiles('test/testbook.pdf'); await p.waitForTimeout(800);
console.log('book listed:', (await p.textContent('#booksPane')).includes('testbook'));
await p.click('#booksPane .entry:has-text("testbook")'); await p.waitForTimeout(2500);
console.log('chapters:', await p.$$eval('#overlay .entry', e=>e.map(x=>x.textContent)));
await p.click('#overlay .entry:has-text("Chapter 2")'); await p.waitForTimeout(800);
console.log('jumped to page:', await p.inputValue('#overlay input[type=number]'));
await p.screenshot({path:'test/f-reader.png'});
await p.keyboard.press('Escape'); await p.click('#tabs button[data-tab=books]');
await p.fill('#booksPane input','stun save'); await p.keyboard.press('Enter'); await p.waitForTimeout(2500);
console.log('search results:', await p.$$eval('#booksPane .entry div:first-child', e=>e.map(x=>x.textContent).filter(t=>/page/.test(t))));
await p.click('#booksPane >> text=Cyberpunk RED >> nth=0'); await p.waitForTimeout(200);
await p.fill('#overlay input','death'); await p.waitForTimeout(200);
console.log('quick ref filter:', (await p.textContent('#overlay')).replace(/\s+/g,' ').slice(0,240));
await p.screenshot({path:'test/f-quickref.png'});
console.log('errors:', errs); await b.close(); })();
